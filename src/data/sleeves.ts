/** Every ticker we hold anywhere, de-duplicated. */
export const ALL_SLEEVE_TICKERS: string[] = [
  ...new Set(SLEEVES.flatMap((s) => s.tickers)),
].sort();

export const sleeveByKey = (key: string): Sleeve | undefined =>
  SLEEVES.find((s) => s.key === key);

/** Which sleeves hold a given ticker. */
export const sleevesHolding = (ticker: string): Sleeve[] =>
  SLEEVES.filter((s) => s.tickers.includes(ticker.toUpperCase()));
